package com.deskpilot.hid

/** Fixed single-collection mouse: three buttons, X/Y, and a vertical wheel. */
object HidDescriptor {
    val basicBytes = byteArrayOf(
        0x05, 0x01,                         // Generic Desktop
        0x09, 0x02,                         // Mouse
        0xA1.toByte(), 0x01,                // Application collection
        0x09, 0x01,                         // Pointer
        0xA1.toByte(), 0x00,                // Physical collection
        0x05, 0x09,                         // Button page
        0x19, 0x01, 0x29, 0x03,             // Buttons 1..3
        0x15, 0x00, 0x25, 0x01,
        0x95.toByte(), 0x03, 0x75, 0x01,
        0x81.toByte(), 0x02,
        0x95.toByte(), 0x01, 0x75, 0x05,
        0x81.toByte(), 0x03,                // Padding
        0x05, 0x01,                         // Generic Desktop
        0x09, 0x30, 0x09, 0x31, 0x09, 0x38, // X, Y, Wheel
        0x15, 0x81.toByte(), 0x25, 0x7F,
        0x75, 0x08, 0x95.toByte(), 0x03,
        0x81.toByte(), 0x06,                // Relative input
        0xC0.toByte(), 0xC0.toByte()
    )

    /** Optional report-mode mouse (wheel + horizontal pan) and six-key keyboard. */
    val advancedBytes = byteArrayOf(
        0x05, 0x01, 0x09, 0x02, 0xA1.toByte(), 0x01, // Mouse
        0x85.toByte(), 0x01, 0x09, 0x01, 0xA1.toByte(), 0x00,
        0x05, 0x09, 0x19, 0x01, 0x29, 0x03, 0x15, 0x00, 0x25, 0x01,
        0x95.toByte(), 0x03, 0x75, 0x01, 0x81.toByte(), 0x02,
        0x95.toByte(), 0x01, 0x75, 0x05, 0x81.toByte(), 0x03,
        0x05, 0x01, 0x09, 0x30, 0x09, 0x31,
        0x15, 0x81.toByte(), 0x25, 0x7F, 0x75, 0x08, 0x95.toByte(), 0x02, 0x81.toByte(), 0x06,
        // Resolution Multiplier makes each wheel/pan unit 1/16th of a normal
        // Windows wheel detent, enabling smooth scrolling and Ctrl+wheel zoom.
        0xA1.toByte(), 0x02, 0x09, 0x48, 0x15, 0x00, 0x25, 0x0F,
        0x35, 0x01, 0x45, 0x10, 0x75, 0x04, 0x95.toByte(), 0x01, 0xB1.toByte(), 0x02,
        0x09, 0x38, 0x15, 0x81.toByte(), 0x25, 0x7F, 0x75, 0x08, 0x95.toByte(), 0x01, 0x81.toByte(), 0x06,
        0xC0.toByte(),
        0xA1.toByte(), 0x02, 0x05, 0x01, 0x09, 0x48, 0x15, 0x00, 0x25, 0x0F,
        0x35, 0x01, 0x45, 0x10, 0x75, 0x04, 0x95.toByte(), 0x01, 0xB1.toByte(), 0x02,
        0x05, 0x0C, 0x0A, 0x38, 0x02, 0x15, 0x81.toByte(), 0x25, 0x7F,
        0x75, 0x08, 0x95.toByte(), 0x01, 0x81.toByte(), 0x06, 0xC0.toByte(),
        0xC0.toByte(), 0xC0.toByte(),
        0x05, 0x01, 0x09, 0x06, 0xA1.toByte(), 0x01, // Keyboard
        0x85.toByte(), 0x02, 0x05, 0x07, 0x19, 0xE0.toByte(), 0x29, 0xE7.toByte(),
        0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95.toByte(), 0x08, 0x81.toByte(), 0x02,
        0x95.toByte(), 0x01, 0x75, 0x08, 0x81.toByte(), 0x03,
        0x95.toByte(), 0x06, 0x75, 0x08, 0x15, 0x00, 0x25, 0x65, 0x05, 0x07,
        0x19, 0x00, 0x29, 0x65, 0x81.toByte(), 0x00, 0xC0.toByte()
    )
}
